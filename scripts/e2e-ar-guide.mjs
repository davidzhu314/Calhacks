import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { chromium } from "playwright";

const base = process.env.E2E_BASE_URL || "http://localhost:3101";
const chromePath = process.env.CHROME_PATH || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const browser = await chromium.launch({ headless: true, ...(existsSync(chromePath) ? { executablePath: chromePath } : {}), args: ["--use-fake-device-for-media-stream", "--use-fake-ui-for-media-stream"] });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, permissions: ["camera"], reducedMotion: "reduce" });
const page = await context.newPage();
const errors = [];
const waitCalls = async (n) => { const end = Date.now() + 9000; while (guideCalls < n && Date.now() < end) await new Promise((r) => setTimeout(r, 100)); assert.equal(guideCalls, n); };
page.on("pageerror", (e) => errors.push(e.message));
let guideCalls = 0;
let checkCalls = 0;
let holdReply = false;
let releaseReply = () => {};
let response = { visible: true, status: "absent", confidence: .95, explanation: "Place the piece", assemblyBox: { left: .25, top: .25, right: .75, bottom: .75 }, partBox: { left: .35, top: .35, right: .45, bottom: .45 }, placement: { x: .55, y: .55 }, orientationDegrees: 0 };
await page.route("**/api/ar-guide", async (route) => { guideCalls++; const reply = response; if (holdReply) await new Promise((resolve) => { releaseReply = resolve; }); await route.fulfill({ json: reply }); });
await page.route("**/api/check", async (route) => { checkCalls++; await route.fulfill({ json: { can_see: true, step_complete: false, confidence: .9, issues: [{ part: "brick", problem: "misaligned", fix: "Move the brick", box: { x: .2, y: .2, w: .1, h: .1 } }], say: "Keep building" } }); });
await page.route("**/api/locate", async (route) => route.fulfill({ json: { callout: null, placed: null } }));
await page.route(/\/api\/(tts|speech-token|where-am-i)/, async (route) => route.abort());
try {
  await page.goto(base);
  await page.evaluate(async () => {
    const db = await new Promise((resolve, reject) => { const req = indexedDB.open("keyval-store", 1); req.onupgradeneeded = () => req.result.createObjectStore("keyval"); req.onsuccess = () => resolve(req.result); req.onerror = () => reject(req.error); });
    await new Promise((resolve, reject) => { const tx = db.transaction("keyval", "readwrite"); tx.objectStore("keyval").put({ id: "t1", source: "lego", title: "AR Test", subtitle: "Local", pdfPath: "/manual-pdf/lego/6455750.pdf", page: 5, addedAt: Date.now(), openedAt: Date.now() }, "manual:t1"); tx.oncomplete = resolve; tx.onerror = () => reject(tx.error); });
    db.close();
  });
  await page.goto(`${base}/build/t1`);
  await page.getByRole("button", { name: "AR Guide" }).waitFor();
  await page.getByRole("heading").first().waitFor({ timeout: 20000 });
  const labelBefore = await page.locator("[aria-label='All steps'] [aria-current='step']").first().getAttribute("aria-label");
  await page.getByRole("button", { name: "AR Guide" }).click();
  await page.getByTestId("ar-placement").waitFor({ timeout: 15000 });
  await page.screenshot({ path: "/tmp/buildsight-ar-guide-mobile.png" });
  assert.equal(guideCalls, 1);
  assert.equal(checkCalls, 0);
  const placement = await page.getByTestId("ar-placement").getAttribute("transform");
  const video = await page.locator("video").evaluate((v) => ({ w: v.videoWidth, h: v.videoHeight, rect: v.getBoundingClientRect().toJSON() }));
  const scale = Math.max(video.rect.width / video.w, video.rect.height / video.h);
  const expectedX = (video.rect.width - video.w * scale) / 2 + .55 * video.w * scale;
  const expectedY = (video.rect.height - video.h * scale) / 2 + .55 * video.h * scale;
  const match = placement.match(/translate\(([-\d.]+) ([-\d.]+)\)/);
  assert.ok(match && Math.abs(Number(match[1]) - expectedX) < 2 && Math.abs(Number(match[2]) - expectedY) < 2, `placement ${placement} expected ${expectedX},${expectedY}`);
  await page.getByRole("button", { name: "Adjust placement" }).click();
  await page.getByRole("button", { name: "Tap camera to place guide" }).click({ position: { x: 320, y: 430 } });
  await page.waitForFunction((before) => document.querySelector('[data-testid="ar-placement"]')?.getAttribute("transform") !== before, placement, { timeout: 5000 });
  const moved = await page.getByTestId("ar-placement").getAttribute("transform");
  assert.notEqual(moved, placement, "manual camera tap moves placement");
  assert.equal(checkCalls, 0);
  await page.getByRole("button", { name: "Reset adjustment" }).click();
  await page.getByTestId("ar-placement").waitFor({ timeout: 15000 });
  assert.equal(guideCalls, 2);
  const labelAfter = await page.locator("[aria-label='All steps'] [aria-current='step']").first().getAttribute("aria-label");
  assert.equal(labelAfter, labelBefore);
  response = { ...response, placement: null };
  await page.getByRole("button", { name: "Rescan" }).click();
  await waitCalls(3);
  await page.getByText("No placement found · tap to position").waitFor();
  assert.equal(await page.getByTestId("ar-placement").count(), 0);
  assert.equal(await page.getByTestId("ar-part").count(), 1);
  response = { ...response, visible: false };
  await page.getByRole("button", { name: "Rescan" }).click();
  await waitCalls(4);
  await page.getByText("Guide lost alignment — rescan or tap to position.").waitFor();
  assert.equal(await page.getByTestId("ar-part").count(), 0);
  response = { ...response, visible: true, placement: { x: .55, y: .55 } };
  await page.getByRole("button", { name: "Rescan" }).click();
  await waitCalls(5);
  await page.getByTestId("ar-placement").waitFor();
  await page.setViewportSize({ width: 844, height: 390 });
  await page.waitForFunction(() => document.querySelector('svg[aria-label="2D AR guide overlay"]')?.getAttribute("viewBox") === "0 0 844 390");
  assert.equal(checkCalls, 0);
  await page.setViewportSize({ width: 390, height: 844 });
  response = { ...response, placement: { x: .4, y: .4 } };
  holdReply = true;
  await page.getByRole("button", { name: "Rescan" }).click();
  await waitCalls(6);
  await page.getByRole("button", { name: "Go to step 2" }).first().click();
  await page.getByRole("heading", { name: /Attach the second green half-circle/ }).waitFor();
  response = { ...response, placement: { x: .6, y: .6 } };
  holdReply = false;
  releaseReply();
  await waitCalls(7);
  await page.getByTestId("ar-placement").waitFor({ timeout: 10000 });
  const newPlacement = await page.getByTestId("ar-placement").getAttribute("transform");
  assert.notEqual(newPlacement, placement, "new step uses its own grounding result");
  await page.getByRole("button", { name: "Check build" }).click();
  await page.waitForFunction(() => document.querySelectorAll('[data-issue-box]').length > 0);
  assert.equal(checkCalls, 1);
  await page.getByRole("button", { name: "Hide guide" }).click();
  await page.getByTestId("ar-placement").waitFor({ state: "hidden" });
  assert.equal(await page.getByTestId("ar-placement").count(), 0);
  assert.deepEqual(errors, []);
  console.log(`AR browser test passed: ${guideCalls} grounding calls, ${checkCalls} check calls, camera ${video.w}×${video.h}`);
} finally {
  await browser.close();
}
